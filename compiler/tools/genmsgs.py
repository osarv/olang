#!/usr/bin/env python3
"""Writes compiler/msgs.olang from bootstrap/errmsg.h's X-macro table (compiler/DESIGN.md section 1.3).

Every entry of the C compiler's table - X(ID, "RULE", "FORMAT") - becomes one olang function taking the format's
directives as typed parameters and returning a Msg: the diagnostic's kind, its rule and its text. So every C message
has its olang twin, and the compiler checks each call's arguments where C's varargs could not.

    %s %S   text: String&                    %d %l   a count: I64
    %n      a token, as a reader sees it: String& (Tok(text), EndOfLine or EndOfFile until M3's Token exists)
    %t      a type, as source writes it: String& (until M5's types exist)
    %c      a byte, escaped where it does not print: Char
    %%      a '%'

Run from the repository root: python3 compiler/tools/genmsgs.py. It rewrites msgs.olang whole, so it is the source of
the generated part until the port's checker (M5) makes %n and %t typed; from then on msgs.olang is edited by hand and
checks/checks.olang holds it to errmsg.h's rules (bootstrap/ takes fixes only).
"""
import re
import sys

HEADER = """\
# msgs - every diagnostic the compiler can give, one function each (compiler/DESIGN.md section 1.3).
#
# A function takes what its message names, typed, and returns a Msg: which diagnostic it is (Kind), the rule of the
# specification it applies (Rule - empty where no rule states it; never an invented one), and the text, lowercase and
# one line with no period at the end (B11). diag records a Msg against where it is about.
#
# GENERATED by compiler/tools/genmsgs.py from bootstrap/errmsg.h - edit the table there and run it again, until M5 makes
# the token and type parameters typed (DESIGN.md), after which this file is edited by hand.
#
# Until then a token parameter (C's %n) is the token as a reader sees it - Tok(text), or EndOfLine or EndOfFile - and a
# type parameter (C's %t) is the type as source writes it.

# a diagnostic: which one it is, the rule it applies, and its text
type Msg struct(Kind Diag, Rule String&, Text String&) {
    Kind
    Rule
    Text
}

# a token as a reader sees it: its text in quotes, each byte that does not print escaped
fn Tok(text String&) String {
    b := StringBuilder()
    b.PushChar('\\'')
    for c in text { b.Push(Esc(c)) }
    b.PushChar('\\'')
    return b.ToString()
}

# the two tokens no text spells
EndOfLine := "end of line"
EndOfFile := "end of file"

# a byte as a message shows it: itself where it prints, else escaped - \\t, \\n, \\r, \\0, or \\xHH
fn Esc(c Char) String {
    if c == '\\t' { return "\\\\t" }
    if c == '\\n' { return "\\\\n" }
    if c == '\\r' { return "\\\\r" }
    if c == '\\0' { return "\\\\0" }
    if U8(c) < 32 or U8(c) >= 127 {
        hex := U8(c).Format(16)
        return "\\\\x" $(hex.PadStart(2, '0'))
    }
    b := StringBuilder()
    b.PushChar(c)
    return b.ToString()
}

"""


TESTS = """
# ---- tests ----

test "a message is its C twin's text, its arguments in their places" {
    m := Expected("'}'", Tok("South"))
    assert m.Text == "expected '}', found 'South'" and m.Rule == "" and m.Kind == Diag.Expected
    assert UnknownChar('@').Rule == "L16"
    assert NoMain().Text == "no main function - a program starts at 'fn main() ? { }'"
}

test "a byte that does not print is escaped, in a character and in a token" {
    assert UnknownChar('\\t').Text == "unexpected character '\\\\t'"
    assert Esc(Char(1)) == "\\\\x01" and Esc(Char(200)) == "\\\\xc8" and Esc('a') == "a"
    assert Tok("a\\nb") == "'a\\\\nb'"
    assert Expected("a name", EndOfLine).Text == "expected a name, found end of line"
}
"""


LIT = r'"(?:[^"\\]|\\.)*"'
ENTRY = re.compile(r'^\s*X\((\w+),\s*(' + LIT + r'),\s*((?:' + LIT + r'\s*)+)\)')


def cstring(lits):
    """The bytes of one or more adjacent C string literals."""
    out = []
    for lit in re.findall(LIT, lits):
        body = lit[1:-1]
        i = 0
        while i < len(body):
            c = body[i]
            if c != '\\':
                out.append(c)
                i += 1
                continue
            e = body[i + 1]
            i += 2
            if e == 'n': out.append('\n')
            elif e == 't': out.append('\t')
            elif e == 'r': out.append('\r')
            elif e == '0': out.append('\0')
            elif e in '\\"\'?': out.append(e)
            elif e == 'x':
                h = re.match(r'[0-9a-fA-F]+', body[i:]).group(0)
                out.append(chr(int(h, 16)))
                i += len(h)
            else:
                raise SystemExit('genmsgs: unknown escape \\' + e)
    return ''.join(out)


def olangLit(text):
    """text as an olang string literal (L14/L15)."""
    out = ['"']
    for c in text:
        if c == '\\': out.append('\\\\')
        elif c == '"': out.append('\\"')
        elif c == '\n': out.append('\\n')
        elif c == '\t': out.append('\\t')
        elif c == '\r': out.append('\\r')
        elif c == '\0': out.append('\\0')
        elif ord(c) < 32 or ord(c) >= 127: raise SystemExit('genmsgs: a byte no olang literal writes: %r' % c)
        else: out.append(c)
    out.append('"')
    return ''.join(out)


def funcName(cid):
    """ERR_UNKNOWN_CHAR is UnknownChar, NOTE_IN_LIBRARY NoteInLibrary."""
    words = cid.split('_')
    if words[0] == 'ERR':
        words = words[1:]
    return ''.join(w[0] + w[1:].lower() for w in words)


# a directive's parameter: its name's stem and its type
KINDS = {'s': ('text', 'String&'), 'S': ('text', 'String&'), 'n': ('tok', 'String&'), 't': ('ty', 'String&'),
         'd': ('n', 'I64'), 'l': ('n', 'I64'), 'c': ('ch', 'Char')}


def function(cid, rule, fmt):
    pieces = []        # literal text and parameter names, in order
    params = []        # (stem, type) in order
    lit = []
    i = 0
    while i < len(fmt):
        c = fmt[i]
        if c != '%':
            lit.append(c)
            i += 1
            continue
        d = fmt[i + 1]
        i += 2
        if d == '%':
            lit.append('%')
            continue
        if d not in KINDS:
            raise SystemExit('genmsgs: %s: unknown directive %%%s' % (cid, d))
        if lit:
            pieces.append(('lit', ''.join(lit)))
            lit = []
        params.append(KINDS[d])
        pieces.append(('par', len(params) - 1, d))
    if lit:
        pieces.append(('lit', ''.join(lit)))
    # a stem used once is its own name; one used more than once is numbered from 1
    counts = {}
    for stem, _ in params:
        counts[stem] = counts.get(stem, 0) + 1
    seen = {}
    names = []
    for stem, _ in params:
        if counts[stem] == 1:
            names.append(stem)
        else:
            seen[stem] = seen.get(stem, 0) + 1
            names.append(stem + str(seen[stem]))
    join = []
    for p in pieces:
        if p[0] == 'lit':
            join.append(olangLit(p[1]))
        elif p[2] == 'c':
            join.append('$Esc(' + names[p[1]] + ')')
        else:
            join.append('$' + names[p[1]])
    text = ' '.join(join) if join else '""'
    name = funcName(cid)
    sig = ', '.join('%s %s' % (n, t) for n, (_, t) in zip(names, params))
    return name, 'fn %s(%s) Msg { return Msg(Diag.%s, %s, %s) }' % (name, sig, name, olangLit(rule), text)


def main():
    src = open('bootstrap/errmsg.h').read()
    table = src[src.index('#define DIAGNOSTICS(X)'):src.index('enum diag {')]
    entries = []
    for line in table.split('\n'):
        if not line.strip().startswith('X('):
            continue
        m = ENTRY.match(line)
        if not m:
            raise SystemExit('genmsgs: cannot read: ' + line)
        entries.append((m.group(1), cstring(m.group(2)), cstring(m.group(3))))
    names = set()
    funcs = []
    for cid, rule, fmt in entries:
        name, fn = function(cid, rule, fmt)
        if name in names:
            raise SystemExit('genmsgs: two entries are named ' + name)
        names.add(name)
        funcs.append((cid, name, fn))
    out = [HEADER]
    out.append('# every diagnostic, in errmsg.h\'s order\n')
    out.append('type Diag enum {\n')
    for _, name, _ in funcs:
        out.append('    %s\n' % name)
    out.append('}\n\n')
    out.append('# errmsg.h\'s entries, one function each, under the C id each comes from\n')
    for cid, _, fn in funcs:
        out.append('\n# %s\n%s\n' % (cid, fn))
    out.append(TESTS)
    open('compiler/msgs.olang', 'w').write(''.join(out))
    print('genmsgs: %d diagnostics written to compiler/msgs.olang' % len(funcs))


if __name__ == '__main__':
    sys.exit(main())
